systems = []
bar = 1
with pymupdf.open(pdf_path) as pdf:
    for page_number, (separators, rows, expected_end) in enumerate(pages, 1):
        page = pdf[page_number - 1]
        ys = [0, *separators, 220 if page_number == 22 else page.rect.height]
        assert len(ys) == len(rows) + 1
        for y0, y1, edges in zip(ys, ys[1:], rows):
            last = bar + len(edges) - 2
            systems.append(dict(page=page_number, fromBar=bar, throughBar=last,
                                crop=[0, y0, page.rect.width, y1], barEdges=edges))
            bar = last + 1
        assert bar - 1 == expected_end, (page_number, bar - 1, expected_end)
assert len(systems) == 89 and bar == 265
